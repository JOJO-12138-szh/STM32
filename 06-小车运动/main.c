/***
 * 文件名: main.c
 * 功能: STM32F10x智能车运动控制测试程序
 * 描述: 演示各种基本运动模式: 直行、后退、左右移动、转向等
 * 硬件: STM32F103系列微控制器 + 四轮驱动小车
 * 作者:
 * 日期:
 ***/

#include "stm32f10x.h" /*** 包含STM32F10x标准外设库头文件 ***/
#include "Car.h"	   /*** 包含小车运动控制函数接口 ***/

/***
 * 函数名: Delay
 * 功能: 简单的延时函数（软件延时，非精确延时）
 * 参数: t - 延时计数（循环次数）
 * 返回值: 无
 * 注意: 此延时依赖于系统时钟频率，建议使用定时器替代
 ***/
void Delay(uint32_t t)
{
	while (t--)
		; /*** 空循环延时，每次循环消耗一个指令周期 ***/
}

/***
 * 函数名: main
 * 功能: 主函数 - 小车运动控制测试
 * 描述: 依次执行各种运动模式，循环演示
 * 流程: 初始化 -> 循环执行运动序列
 ***/
int main(void)
{
	// 初始化小车：配置GPIO、PWM定时器等硬件资源
	Car_Init();

	// 主循环：无限循环执行运动测试序列
	while (1)
	{
		// ========== 直行运动测试 ==========
		Car_GoStraight(); // 所有车轮向前转动
		Delay(50000000);  // 延时约1-2秒（根据时钟频率）

		// ========== 停止测试 ==========
		Car_Stop();		 // 所有车轮制动
		Delay(10000000); // 短暂停顿，便于观察状态切换

		// ========== 后退运动测试 ==========
		Car_GoBack(); // 所有车轮向后转动
		Delay(50000000);

		Car_Stop(); // 停止
		Delay(10000000);

		// ========== 左平移运动测试 ==========
		Car_LeftMove(); // 左侧车轮后退，右侧车轮前进（原地左移）
		Delay(50000000);

		Car_Stop();
		Delay(10000000);

		// ========== 右平移运动测试 ==========
		Car_RightMove(); // 左侧车轮前进，右侧车轮后退（原地右移）
		Delay(50000000);

		Car_Stop();
		Delay(10000000);

		// ========== 左转向测试 ==========
		Car_TurnLeft(); // 两轮差速左转
		Delay(50000000);

		Car_Stop();
		Delay(10000000);

		// ========== 右转向测试 ==========
		Car_TurnRight(); // 两轮差速右转
		Delay(50000000);

		Car_Stop();
		Delay(10000000);

		// ========== 左前转向测试 ==========
		Car_ForwardLeft(); // 左后轮停止/反转，右前轮前进（向左前方转弯）
		Delay(50000000);

		// ========== 右前转向测试 ==========
		Car_ForwardRight(); // 左前轮前进，右后轮停止/反转（向右前方转弯）
		Delay(50000000);

		// ========== 左后转向测试 ==========
		Car_BackwardLeft(); // 向左后方转弯
		Delay(50000000);

		// ========== 右后转向测试 ==========
		Car_BackwardRight(); // 向右后方转弯
		Delay(50000000);

		// ========== 前左原地转向测试 ==========
		Car_PivotFrontLeft(); // 以前轴为支点左转
		Delay(50000000);

		// ========== 前右原地转向测试 ==========
		Car_PivotFrontRight(); // 以前轴为支点右转
		Delay(50000000);

		// ========== 后左原地转向测试 ==========
		Car_PivotRearLeft(); // 以后轴为支点左转
		Delay(50000000);

		// ========== 后右原地转向测试 ==========
		Car_PivotRearRight(); // 以后轴为支点右转
		Delay(50000000);

		// 所有模式执行完毕，循环重新开始
	}
}